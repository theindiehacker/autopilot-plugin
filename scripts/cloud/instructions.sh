#!/usr/bin/env bash
# セッションの開始・再開・要約の後に、ユーザーからの指示を Claude に渡す (stdout が文脈に入る)

# ローカルでもクラウドでも出す (autopilot を入れたすべてのセッションに効かせるため)
cat << 'MSG'
ユーザーからの指示:
- 作業の途中の進み具合は、メッセージに書かない。書くのは、ユーザーに聞くことがあるときと、作業を終えたときだけにする。
- ユーザーは、任せている間は画面を見ていない。途中のメッセージは読まれず、文脈を使うだけになる。
- 聞くときは、前のやり取りを読まなくても分かるように、前提・選べる案・おすすめを書く。
- 終えたときは、したこと・確かめたこと・ユーザーがすることを短くまとめる。
MSG

# ここから下はクラウドだけ。ローカルでは出さない
[ "${CLAUDE_CODE_REMOTE:-}" = "true" ] || exit 0

cat << 'MSG'
- 自分の作った PR を claude[bot] のレビューが下書きに戻したときは、指摘を直す (または返信する) push をして CI が通ったら、ユーザーに聞かずに「レビュー可能」に戻してよい (update_pull_request で draft: false)。
- ほかの人が下書きに戻した PR は戻さない。
MSG
